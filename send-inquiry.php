
<?php

header('Content-Type: application/json; charset=UTF-8');

function respond(int $status, array $data): void
{
    http_response_code($status);
    echo json_encode($data);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    respond(405, [
        'success' => false,
        'message' => 'Method not allowed.'
    ]);
}

$firstName = trim($_POST['first_name'] ?? '');
$lastName  = trim($_POST['last_name'] ?? '');
$email     = trim($_POST['email'] ?? '');
$phone     = trim($_POST['phone'] ?? '');
$website   = trim($_POST['website'] ?? '');

$socialLinks = trim($_POST['social_links'] ?? '');
$competitors = trim($_POST['competitors'] ?? '');

$growthGoal = trim($_POST['growth_goal'] ?? '');
$budget     = trim($_POST['budget'] ?? '');
$challenge  = trim($_POST['challenge'] ?? '');

// Validate required fields.
if (
    !$firstName ||
    !$lastName ||
    !$email ||
    !$website ||
    !$growthGoal ||
    !$budget
) {
    respond(422, [
        'success' => false,
        'message' => 'Please complete all required fields.'
    ]);
}

if (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
    respond(422, [
        'success' => false,
        'message' => 'Please enter a valid email address.'
    ]);
}

if (!filter_var($website, FILTER_VALIDATE_URL)) {
    respond(422, [
        'success' => false,
        'message' => 'Please enter a valid website URL.'
    ]);
}

// Escape user input before inserting it into HTML.
function e(string $value): string
{
    return htmlspecialchars($value, ENT_QUOTES, 'UTF-8');
}

// CHANGE THIS TO YOUR ACTUAL ENQUIRY EMAIL.
$recipientEmail = 'info@wedocollective.co.za';

$subject = 'New Website Enquiry - WeDo Collective';

$fullName = $firstName . ' ' . $lastName;

$sections = [
    'About You' => [
        'Full Name' => $fullName,
        'Email' => $email,
        'Phone' => $phone ?: 'Not provided',
        'Website' => $website,
    ],
    'Digital Presence' => [
        'Social Media Links' => $socialLinks ?: 'Not provided',
        'Competitors' => $competitors ?: 'Not provided',
    ],
    'Growth Goals' => [
        'Primary Growth Goal' => $growthGoal,
        'Monthly Marketing Budget' => $budget,
        'Biggest Growth Challenge' => $challenge ?: 'Not provided',
    ],
];

$sectionsHtml = '';

foreach ($sections as $heading => $items) {
    $sectionsHtml .= '
        <h2 style="color:#E87536;font-size:17px;margin:30px 0 12px;">
            ' . e($heading) . '
        </h2>
        <table width="100%" cellpadding="10"
            cellspacing="0" style="border-collapse:collapse;">
    ';

    foreach ($items as $label => $value) {
        $sectionsHtml .= '
            <tr>
                <td width="35%" valign="top"
                    style="border-bottom:1px solid #eeeeee;color:#777;font-size:13px;">
                    ' . e($label) . '
                </td>
                <td valign="top"
                    style="border-bottom:1px solid #eeeeee;color:#222;font-size:13px;white-space:pre-wrap;">
                    ' . nl2br(e($value)) . '
                </td>
            </tr>
        ';
    }

    $sectionsHtml .= '</table>';
}

$htmlMessage = '
<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8">
</head>
<body style="margin:0;padding:15px;background:#f4f4f4;font-family:Arial,sans-serif;">

    <div style="max-width:600px;margin:auto;background:#ffffff;">

        <div style="background:#171717;padding:18px 22px;color:#ffffff;">
            <h1 style="margin:0;font-size:20px;">WeDo Collective</h1>
            <p style="margin:4px 0 0;color:#cccccc;font-size:12px;">
                New Website Enquiry
            </p>
        </div>

        <div style="padding:20px 22px;">

            <h2 style="margin:0 0 8px;font-size:17px;color:#171717;">
                A new enquiry has arrived.
            </h2>

            <p style="margin:0 0 15px;font-size:13px;line-height:1.5;color:#666666;">
                Someone has submitted an enquiry through your website.
                Below are the submitted details:
            </p>

            ' . $sectionsHtml . '

            <p style="margin:20px 0 0;padding-top:12px;border-top:1px solid #eeeeee;color:#999999;font-size:11px;line-height:1.5;">
                Automatically generated by the WeDo Collective website.
            </p>

        </div>

        <div style="background:#171717;padding:12px;text-align:center;">
            <p style="margin:0;color:#cccccc;font-size:11px;">
                &copy; WeDo Collective
            </p>
        </div>

    </div>

</body>
</html>
';

$headers = [
    'MIME-Version: 1.0',
    'Content-Type: text/html; charset=UTF-8',
    'From: WeDo Collective <no-reply@wedocollective.co.za>',
    'Reply-To: ' . $email,
    'X-Mailer: PHP/' . phpversion(),
];

$sent = mail(
    $recipientEmail,
    $subject,
    $htmlMessage,
    implode("\r\n", $headers)
);

if (!$sent) {
    respond(500, [
        'success' => false,
        'message' => 'We could not send your enquiry. Please try again later.'
    ]);
}

respond(200, [
    'success' => true,
    'message' => 'Thank you! Your enquiry has been submitted successfully. Our team will be in touch.'
]);
